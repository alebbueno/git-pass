//! Global Git hooks managed via `core.hooksPath`.

use std::fmt;
use std::fs;
use std::io;
#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::str::FromStr;

use crate::ensure_app_support_exists;

/// Subdirectory under Application Support containing hook scripts.
pub const HOOKS_DIR_NAME: &str = "hooks";

/// Hook phases we install (Git hook filename = phase name).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HookPhase {
    PreCommit,
    PreMergeCommit,
    CommitMsg,
    PrepareCommitMsg,
    PostCommit,
    PreRebase,
    PrePush,
}

impl HookPhase {
    pub fn file_name(self) -> &'static str {
        match self {
            HookPhase::PreCommit => "pre-commit",
            HookPhase::PreMergeCommit => "pre-merge-commit",
            HookPhase::CommitMsg => "commit-msg",
            HookPhase::PrepareCommitMsg => "prepare-commit-msg",
            HookPhase::PostCommit => "post-commit",
            HookPhase::PreRebase => "pre-rebase",
            HookPhase::PrePush => "pre-push",
        }
    }

    pub fn cli_phase(self) -> &'static str {
        self.file_name()
    }

    pub fn all_v1() -> &'static [HookPhase] {
        &[
            HookPhase::PreCommit,
            HookPhase::PreMergeCommit,
            HookPhase::CommitMsg,
            HookPhase::PrepareCommitMsg,
            HookPhase::PostCommit,
            HookPhase::PreRebase,
            HookPhase::PrePush,
        ]
    }
}

impl fmt::Display for HookPhase {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.file_name())
    }
}

impl FromStr for HookPhase {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "pre-commit" => Ok(HookPhase::PreCommit),
            "pre-merge-commit" => Ok(HookPhase::PreMergeCommit),
            "commit-msg" => Ok(HookPhase::CommitMsg),
            "prepare-commit-msg" => Ok(HookPhase::PrepareCommitMsg),
            "post-commit" => Ok(HookPhase::PostCommit),
            "pre-rebase" => Ok(HookPhase::PreRebase),
            "pre-push" => Ok(HookPhase::PrePush),
            other => Err(format!("unknown hook phase: {other}")),
        }
    }
}

/// `~/Library/Application Support/.../hooks`
pub fn hooks_dir() -> Result<PathBuf, io::Error> {
    Ok(ensure_app_support_exists()?.join(HOOKS_DIR_NAME))
}

/// Shell script body: delegates to `gitpass hook run` with embedded binary path.
pub fn hook_script(gitpass_bin: &Path, phase: HookPhase) -> String {
    let bin = gitpass_bin.to_string_lossy().replace('\'', "'\\''");
    format!(
        r#"#!/bin/sh
# Generated by GitPass — do not edit by hand (run: gitpass hooks install)
export GITPASS_HOOK=1
exec '{bin}' hook run --phase {phase} -- "$@"
"#,
        bin = bin,
        phase = phase.cli_phase()
    )
}

/// Write all v1 hook scripts and set permissions to 0o755.
pub fn write_hook_scripts(gitpass_bin: &Path) -> Result<(), io::Error> {
    let dir = hooks_dir()?;
    fs::create_dir_all(&dir)?;
    for phase in HookPhase::all_v1() {
        let path = dir.join(phase.file_name());
        let body = hook_script(gitpass_bin, *phase);
        fs::write(&path, body)?;
        #[cfg(unix)]
        {
            let perm = fs::Permissions::from_mode(0o755);
            fs::set_permissions(&path, perm)?;
        }
    }
    Ok(())
}

/// True if every expected hook file exists and is executable (owner execute bit).
pub fn hooks_installed_ok(gitpass_bin: &Path) -> Result<bool, io::Error> {
    let dir = hooks_dir()?;
    if !dir.is_dir() {
        return Ok(false);
    }
    for phase in HookPhase::all_v1() {
        let path = dir.join(phase.file_name());
        if !path.is_file() {
            return Ok(false);
        }
        #[cfg(unix)]
        {
            let meta = fs::metadata(&path)?;
            let mode = meta.permissions().mode();
            if mode & 0o100 == 0 {
                return Ok(false);
            }
        }
        // Quick sanity: first line should reference gitpass (generated file)
        let head = fs::read_to_string(&path).unwrap_or_default();
        if !head.contains("GitPass") {
            return Ok(false);
        }
        let expected = hook_script(gitpass_bin, *phase);
        if fs::read_to_string(&path).unwrap_or_default() != expected {
            return Ok(false);
        }
    }
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hook_script_contains_phase() {
        let p = Path::new("/usr/local/bin/gitpass");
        let s = hook_script(p, HookPhase::PreCommit);
        assert!(s.contains("pre-commit"));
        assert!(s.contains("/usr/local/bin/gitpass"));
    }
}
