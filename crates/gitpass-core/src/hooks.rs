//! Global Git hooks managed via `core.hooksPath`.

use std::fmt;
use std::fs;
use std::io;
#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::str::FromStr;

use crate::ensure_app_support_exists;

/// Subdirectory under Application Support containing hook scripts.
pub const HOOKS_DIR_NAME: &str = "hooks";

/// Hook phases we install (Git hook filename = phase name).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HookPhase {
    PreCommit,
    PreMergeCommit,
    CommitMsg,
    PrepareCommitMsg,
    PostCommit,
    PreRebase,
    PrePush,
}

impl HookPhase {
    pub fn file_name(self) -> &'static str {
        match self {
            HookPhase::PreCommit => "pre-commit",
            HookPhase::PreMergeCommit => "pre-merge-commit",
            HookPhase::CommitMsg => "commit-msg",
            HookPhase::PrepareCommitMsg => "prepare-commit-msg",
            HookPhase::PostCommit => "post-commit",
            HookPhase::PreRebase => "pre-rebase",
            HookPhase::PrePush => "pre-push",
        }
    }

    pub fn cli_phase(self) -> &'static str {
        self.file_name()
    }

    pub fn all_v1() -> &'static [HookPhase] {
        &[
            HookPhase::PreCommit,
            HookPhase::PreMergeCommit,
            HookPhase::CommitMsg,
            HookPhase::PrepareCommitMsg,
            HookPhase::PostCommit,
            HookPhase::PreRebase,
            HookPhase::PrePush,
        ]
    }
}

impl fmt::Display for HookPhase {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.file_name())
    }
}

impl FromStr for HookPhase {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "pre-commit" => Ok(HookPhase::PreCommit),
            "pre-merge-commit" => Ok(HookPhase::PreMergeCommit),
            "commit-msg" => Ok(HookPhase::CommitMsg),
            "prepare-commit-msg" => Ok(HookPhase::PrepareCommitMsg),
            "post-commit" => Ok(HookPhase::PostCommit),
            "pre-rebase" => Ok(HookPhase::PreRebase),
            "pre-push" => Ok(HookPhase::PrePush),
            other => Err(format!("unknown hook phase: {other}")),
        }
    }
}

/// `~/Library/Application Support/.../hooks`
pub fn hooks_dir() -> Result<PathBuf, io::Error> {
    Ok(ensure_app_support_exists()?.join(HOOKS_DIR_NAME))
}

fn config_path() -> PathBuf {
    crate::config_file_path().unwrap_or_else(|_| PathBuf::from(crate::CONFIG_FILE_NAME))
}

/// Hook script for `phase`, calling `gitpass_bin` without chaining to a previous global hooks
/// directory. Same body as [`crate::integration::hook_script`], which `integration::apply`
/// installs (with chaining); prefer `integration::apply` over writing scripts directly.
pub fn hook_script(gitpass_bin: &Path, phase: HookPhase) -> String {
    crate::integration::hook_script(phase.cli_phase(), true, gitpass_bin, &config_path(), None)
}

/// Writes every GitPass hook script (validated phases and pass-through hooks) into [`hooks_dir`].
/// Does not touch `core.hooksPath`; `integration::apply` does both.
pub fn write_hook_scripts(gitpass_bin: &Path) -> Result<(), io::Error> {
    let dir = hooks_dir()?;
    fs::create_dir_all(&dir)?;
    for (name, body) in crate::integration::hook_scripts(gitpass_bin, &config_path(), None) {
        let path = dir.join(name);
        fs::write(&path, body)?;
        #[cfg(unix)]
        fs::set_permissions(&path, fs::Permissions::from_mode(0o755))?;
    }
    Ok(())
}

/// True if every validated phase has an executable GitPass script that calls `gitpass_bin` with
/// the current syntax (`hook --phase`). Chaining is not compared; `integration::status` does the
/// full check.
pub fn hooks_installed_ok(gitpass_bin: &Path) -> Result<bool, io::Error> {
    let dir = hooks_dir()?;
    if !dir.is_dir() {
        return Ok(false);
    }
    let bin_line = format!(
        "gitpass_bin={}",
        crate::integration::sh_quote(&gitpass_bin.to_string_lossy())
    );
    for phase in HookPhase::all_v1() {
        let path = dir.join(phase.file_name());
        let Ok(meta) = fs::metadata(&path) else {
            return Ok(false);
        };
        #[cfg(unix)]
        if !meta.is_file() || meta.permissions().mode() & 0o100 == 0 {
            return Ok(false);
        }
        #[cfg(not(unix))]
        if !meta.is_file() {
            return Ok(false);
        }
        let body = fs::read_to_string(&path).unwrap_or_default();
        if !body.contains("Generated by GitPass")
            || !body.contains(" hook --phase ")
            || !body.lines().any(|l| l == bin_line)
        {
            return Ok(false);
        }
    }
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hook_script_uses_cli_syntax_and_only_validates_bound_repos() {
        let p = Path::new("/usr/local/bin/gitpass");
        let s = hook_script(p, HookPhase::PreCommit);
        assert!(s.contains("gitpass_phase='pre-commit'"));
        assert!(s.contains("gitpass_bin='/usr/local/bin/gitpass'"));
        assert!(s.contains(r#""$gitpass_bin" hook --phase "$gitpass_phase""#));
        assert!(!s.contains("hook run"));
        assert!(s.contains("grep -qF \"root_path = "));
    }

    #[test]
    fn every_phase_round_trips_through_from_str() {
        for p in HookPhase::all_v1() {
            assert_eq!(HookPhase::from_str(p.cli_phase()).unwrap(), *p);
        }
    }
}
