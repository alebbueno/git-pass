/// Where the integration reads and writes. [`IntegrationEnv::system`] is the real machine.
#[derive(Debug, Clone)]
pub struct IntegrationEnv {
    /// `~/Library/Application Support/com.gitpass.GitPass`.
    pub app_support: PathBuf,
    /// Directory holding the bundled binaries (`GitPass.app/Contents/MacOS`, or `target/<profile>` in dev).
    pub sidecar_dir: Option<PathBuf>,
    /// `None` = the user's real global Git config. `Some` sets `GIT_CONFIG_GLOBAL` (and ignores the system config).
    pub git_global_config: Option<PathBuf>,
    /// `~/Library/LaunchAgents`; `None` disables daemon management (tests, non-macOS).
    pub launch_agents_dir: Option<PathBuf>,
    /// Used to expand `~` in `core.hooksPath`.
    pub home: Option<PathBuf>,
}

impl IntegrationEnv {
    pub fn system(sidecar_dir: Option<PathBuf>) -> io::Result<Self> {
        let home = dirs::home_dir();
        let launch_agents_dir = if cfg!(target_os = "macos") {
            home.as_ref().map(|h| h.join("Library/LaunchAgents"))
        } else {
            None
        };
        Ok(Self {
            app_support: crate::app_support_dir()?,
            sidecar_dir,
            git_global_config: None,
            launch_agents_dir,
            home,
        })
    }

    pub fn bin_dir(&self) -> PathBuf {
        self.app_support.join(BIN_DIR_NAME)
    }

    pub fn bin_path(&self, s: Sidecar) -> PathBuf {
        self.bin_dir().join(s.name)
    }

    pub fn hooks_dir(&self) -> PathBuf {
        self.app_support.join(HOOKS_DIR_NAME)
    }

    pub fn config_file(&self) -> PathBuf {
        self.app_support.join(CONFIG_FILE_NAME)
    }

    pub fn backup_file(&self) -> PathBuf {
        self.app_support.join(BACKUP_FILE_NAME)
    }

    pub fn disabled_marker(&self) -> PathBuf {
        self.app_support.join(DISABLED_MARKER_NAME)
    }

    pub fn socket_path(&self) -> PathBuf {
        self.app_support.join("gitpassd.sock")
    }

    pub fn daemon_log(&self) -> PathBuf {
        self.app_support.join(LOGS_DIR_NAME).join("gitpassd.log")
    }

    pub fn launch_agent_plist(&self) -> Option<PathBuf> {
        self.launch_agents_dir
            .as_ref()
            .map(|d| d.join(format!("{LAUNCH_AGENT_LABEL}.plist")))
    }
}

