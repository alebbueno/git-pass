fn undo_credentials(g: &GitConfig, backup: Option<&CredentialBackup>, changes: &mut Vec<String>) -> Result<(), String> {
    let values = g.get_all(CREDENTIAL_HELPER_KEY)?;
    if !values.iter().any(|v| is_gitpass_helper(v)) {
        return Ok(());
    }
    g.unset_all(CREDENTIAL_HELPER_KEY)?;
    let restore = match backup {
        Some(b) => b.github_helpers.clone(),
        None => normalize_previous_helpers(&values),
    };
    for h in &restore {
        g.add(CREDENTIAL_HELPER_KEY, h)?;
    }
    if let Some(b) = backup {
        match &b.use_http_path {
            Some(v) => g.set(CREDENTIAL_USE_HTTP_PATH_KEY, v)?,
            None => g.unset_all(CREDENTIAL_USE_HTTP_PATH_KEY)?,
        }
    }
    g.remove_section_if_empty(CREDENTIAL_SECTION, CREDENTIAL_SECTION_REGEX);
    changes.push(if restore.iter().any(|h| !h.is_empty()) {
        "Credenciais do GitHub restauradas como estavam.".into()
    } else {
        "As credenciais do GitHub não passam mais pelo GitPass.".into()
    });
    Ok(())
}

fn undo_hooks(env: &IntegrationEnv, g: &GitConfig, backup: Option<&HooksBackup>, changes: &mut Vec<String>) -> Result<(), String> {
    let current = g.get(HOOKS_PATH_KEY)?;
    if classify_hooks_path(current.as_deref(), &env.hooks_dir(), env.home.as_deref()) == HooksPathState::Managed {
        let previous = match backup {
            Some(b) => b.previous_hooks_path.clone(),
            None => g.get(LEGACY_HOOKS_BACKUP_KEY)?,
        };
        match &previous {
            Some(p) => g.set(HOOKS_PATH_KEY, p)?,
            None => g.unset_all(HOOKS_PATH_KEY)?,
        }
        changes.push(match previous {
            Some(p) => format!("Verificações globais restauradas para {p}."),
            None => "Verificações do GitPass removidas.".into(),
        });
    }
    g.unset_all(LEGACY_HOOKS_BACKUP_KEY)?;
    g.remove_section_if_empty(LEGACY_HOOKS_BACKUP_SECTION, LEGACY_HOOKS_BACKUP_REGEX);
    if let Ok(rd) = fs::read_dir(env.hooks_dir()) {
        for e in rd.flatten() {
            let p = e.path();
            if fs::read_to_string(&p).is_ok_and(|s| s.contains(HOOK_MARKER)) {
                let _ = fs::remove_file(&p);
            }
        }
    }
    Ok(())
}

/// Restores the backup, unregisters `gitpassd`, removes the copied binaries and keeps the app
/// from re-applying on its own (until [`apply`] runs again).
pub fn undo(env: &IntegrationEnv) -> Result<IntegrationReport, String> {
    let _g = lock();
    fs::create_dir_all(&env.app_support).map_err(|e| e.to_string())?;
    fs::write(env.disabled_marker(), b"")
        .map_err(|e| format!("Não foi possível desativar a integração: {e}"))?;
    let mut changes = Vec::new();
    let mut warnings = Vec::new();

    if let Some(plist) = env.launch_agent_plist() {
        if plist.exists() {
            if let Err(e) = agent_bootout() {
                warnings.push(e);
            }
            let _ = fs::remove_file(&plist);
            changes.push("Serviço em segundo plano removido.".into());
        }
    }

    let backup = load_backup(env)?;
    let g = GitConfig::new(env)?;
    undo_credentials(&g, backup.as_ref().and_then(|b| b.credential.as_ref()), &mut changes)?;
    undo_hooks(env, &g, backup.as_ref().and_then(|b| b.hooks.as_ref()), &mut changes)?;

    for s in SIDECARS {
        let _ = fs::remove_file(env.bin_path(s));
    }
    let _ = fs::remove_dir(env.bin_dir());
    let _ = fs::remove_file(env.backup_file());
    Ok(IntegrationReport {
        status: status_unlocked(env),
        changes,
        warnings,
    })
}

