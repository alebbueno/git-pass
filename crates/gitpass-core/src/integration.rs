/// Copies bundled binaries to `bin/` when they differ. Returns whether `gitpassd` changed.
fn sync_binaries(env: &IntegrationEnv, changes: &mut Vec<String>) -> Result<bool, String> {
    let mut daemon_updated = false;
    let mut missing = Vec::new();
    for s in SIDECARS {
        let dest = env.bin_path(s);
        match read_bundled(env, s) {
            Some(bytes) => {
                let current = fs::read(&dest).ok();
                if current.as_deref() != Some(bytes.as_slice()) || !is_executable(&dest) {
                    write_atomic(&dest, &bytes, 0o755).map_err(|e| {
                        format!("Não foi possível instalar {} em {}: {e}", s.name, env.bin_dir().display())
                    })?;
                    changes.push(format!("Peça da integração instalada: {}.", s.name));
                    daemon_updated |= s == SIDECAR_DAEMON;
                }
            }
            None if !is_executable(&dest) => missing.push(s.name),
            None => {}
        }
    }
    if missing.is_empty() {
        Ok(daemon_updated)
    } else {
        Err(format!(
            "Esta instalação do GitPass não inclui as peças da integração ({}). Instale o app de novo a partir do arquivo original.",
            missing.join(", ")
        ))
    }
}

fn apply_credentials(
    env: &IntegrationEnv,
    g: &GitConfig,
    backup: &mut IntegrationBackup,
    changes: &mut Vec<String>,
) -> Result<(), String> {
    let values = g.get_all(CREDENTIAL_HELPER_KEY)?;
    let use_http_path = g.get(CREDENTIAL_USE_HTTP_PATH_KEY)?;
    let expected = credential_helper_value(&env.bin_path(SIDECAR_CREDENTIAL));
    let state = credential_state(&values, use_http_path.as_deref(), &expected);
    if state == CredentialState::Ok {
        return Ok(());
    }
    if backup.credential.is_none() {
        backup.credential = Some(CredentialBackup {
            github_helpers: normalize_previous_helpers(&values),
            use_http_path: use_http_path.clone(),
        });
        save_backup(env, backup)?;
    }
    g.unset_all(CREDENTIAL_HELPER_KEY)?;
    g.add(CREDENTIAL_HELPER_KEY, "")?;
    g.add(CREDENTIAL_HELPER_KEY, &expected)?;
    g.set(CREDENTIAL_USE_HTTP_PATH_KEY, "true")?;
    changes.push(match state {
        CredentialState::Conflict(prev) => {
            format!("As credenciais do GitHub agora vêm do GitPass (substituído: {prev}; salvo para restaurar).")
        }
        _ => "Credenciais do GitHub configuradas.".to_string(),
    });
    Ok(())
}

fn write_hooks(env: &IntegrationEnv, next: Option<&Path>) -> Result<bool, String> {
    if hooks_up_to_date(env, next) {
        return Ok(false);
    }
    let dir = env.hooks_dir();
    let fail = |e: io::Error| format!("Não foi possível gravar as verificações do Git em {}: {e}", dir.display());
    fs::create_dir_all(&dir).map_err(fail)?;
    #[cfg(unix)]
    fs::set_permissions(&dir, fs::Permissions::from_mode(0o700)).map_err(fail)?;
    for (name, body) in expected_hooks(env, next) {
        write_atomic(&dir.join(&name), body.as_bytes(), 0o755).map_err(fail)?;
    }
    Ok(true)
}

fn apply_hooks(
    env: &IntegrationEnv,
    g: &GitConfig,
    backup: &mut IntegrationBackup,
    take_over: bool,
    changes: &mut Vec<String>,
    warnings: &mut Vec<String>,
) -> Result<(), String> {
    let current = g.get(HOOKS_PATH_KEY)?;
    let managed = env.hooks_dir();
    let managed_str = managed.to_string_lossy().into_owned();
    match classify_hooks_path(current.as_deref(), &managed, env.home.as_deref()) {
        HooksPathState::Managed => {
            if backup.hooks.is_none() {
                // Installed by `gitpass hooks install`: adopt its git-config backup.
                backup.hooks = Some(HooksBackup {
                    previous_hooks_path: g.get(LEGACY_HOOKS_BACKUP_KEY)?,
                });
                save_backup(env, backup)?;
            }
            if write_hooks(env, chain_dir(env, g, backup).as_deref())? {
                changes.push("Verificações do Git atualizadas.".into());
            }
        }
        HooksPathState::NotSet => {
            if backup.hooks.is_none() {
                backup.hooks = Some(HooksBackup::default());
                save_backup(env, backup)?;
            }
            write_hooks(env, chain_dir(env, g, backup).as_deref())?;
            g.set(HOOKS_PATH_KEY, &managed_str)?;
            changes.push("Verificações do Git instaladas.".into());
        }
        HooksPathState::Foreign(prev) if take_over => {
            backup.hooks = Some(HooksBackup {
                previous_hooks_path: Some(prev.clone()),
            });
            save_backup(env, backup)?;
            write_hooks(env, chain_dir(env, g, backup).as_deref())?;
            g.set(HOOKS_PATH_KEY, &managed_str)?;
            changes.push(format!("Verificações do GitPass ativas; as suas verificações em {prev} continuam rodando depois."));
        }
        HooksPathState::Foreign(prev) => {
            warnings.push(format!(
                "As verificações do GitPass não foram instaladas porque o Git já usa verificações globais em {prev}. Em Configurações, você pode encadeá-las."
            ));
        }
    }
    Ok(())
}

fn apply_daemon(env: &IntegrationEnv, binary_updated: bool, changes: &mut Vec<String>) -> Result<(), String> {
    let Some(plist) = env.launch_agent_plist() else {
        return Ok(());
    };
    fs::create_dir_all(env.app_support.join(LOGS_DIR_NAME)).map_err(|e| e.to_string())?;
    trim_daemon_log(env);
    let expected = launch_agent_plist(&env.bin_path(SIDECAR_DAEMON), &env.daemon_log());
    let plist_changed = fs::read_to_string(&plist).ok().as_deref() != Some(expected.as_str());
    if plist_changed {
        write_atomic(&plist, expected.as_bytes(), 0o644)
            .map_err(|e| format!("Não foi possível registrar o serviço em {}: {e}", plist.display()))?;
    }
    let loaded = agent_loaded();
    if loaded && plist_changed {
        agent_bootout()?;
        agent_bootstrap(&plist)?;
    } else if !loaded {
        agent_bootstrap(&plist)?;
    } else if binary_updated || ping_daemon(&env.socket_path(), Duration::from_millis(500)).is_err() {
        agent_kickstart()?;
    } else {
        return Ok(());
    }
    wait_for_daemon(&env.socket_path(), Duration::from_secs(3))
        .map_err(|_| "O serviço do GitPass foi iniciado, mas ainda não responde. Tente Reiniciar daqui a pouco.".to_string())?;
    changes.push(if plist_changed {
        "Serviço em segundo plano registrado e iniciado.".into()
    } else {
        "Serviço em segundo plano reiniciado.".into()
    });
    Ok(())
}

/// Installs or repairs everything. Re-enables the integration if it had been undone.
pub fn apply(env: &IntegrationEnv, opts: ApplyOptions) -> Result<IntegrationReport, String> {
    let _g = lock();
    fs::create_dir_all(&env.app_support)
        .map_err(|e| format!("Não foi possível criar {}: {e}", env.app_support.display()))?;
    // Holds the binaries Git executes, the hooks and the config they read: owner-only.
    #[cfg(unix)]
    fs::set_permissions(&env.app_support, fs::Permissions::from_mode(0o700))
        .map_err(|e| format!("Não foi possível proteger {}: {e}", env.app_support.display()))?;
    let _ = fs::remove_file(env.disabled_marker());
    let mut changes = Vec::new();
    let mut warnings = Vec::new();

    let daemon_updated = sync_binaries(env, &mut changes)?;
    let g = GitConfig::new(env)?;
    let mut backup = load_backup(env)?.unwrap_or_else(|| IntegrationBackup {
        version: 1,
        created_at: Some(chrono::Utc::now().to_rfc3339()),
        ..Default::default()
    });
    apply_credentials(env, &g, &mut backup, &mut changes)?;
    apply_hooks(env, &g, &mut backup, opts.take_over_hooks, &mut changes, &mut warnings)?;
    if let Err(e) = apply_daemon(env, daemon_updated, &mut changes) {
        warnings.push(e);
    }
    Ok(IntegrationReport {
        status: status_unlocked(env),
        changes,
        warnings,
    })
}

/// Startup entry point: applies unless the user undid the integration.
pub fn autostart(env: &IntegrationEnv) -> Result<Option<IntegrationReport>, String> {
    if env.disabled_marker().exists() {
        return Ok(None);
    }
    apply(env, ApplyOptions::default()).map(Some)
}

