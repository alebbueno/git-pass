// --- Filesystem helpers ---

pub(crate) fn write_atomic(path: &Path, bytes: &[u8], mode: u32) -> io::Result<()> {
    let parent = path
        .parent()
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "path without parent"))?;
    fs::create_dir_all(parent)?;
    let name = path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let tmp = parent.join(format!(".{name}.tmp-{}", std::process::id()));
    let _ = fs::remove_file(&tmp);
    {
        let mut opts = fs::OpenOptions::new();
        // `create_new` never follows a symlink planted at `tmp`; the mode applies from creation, so
        // private files (backup) are never briefly readable by others.
        opts.write(true).create_new(true);
        #[cfg(unix)]
        std::os::unix::fs::OpenOptionsExt::mode(&mut opts, mode);
        let mut f = opts.open(&tmp)?;
        f.write_all(bytes)?;
        f.sync_all()?;
    }
    // The umask may have masked bits at creation (e.g. 0o755 → 0o755 & !umask).
    #[cfg(unix)]
    fs::set_permissions(&tmp, fs::Permissions::from_mode(mode))?;
    #[cfg(not(unix))]
    let _ = mode;
    // Rename gives a new inode: a running helper/daemon keeps its old image and macOS never sees a
    // binary modified in place (which would invalidate its code signature).
    fs::rename(&tmp, path).inspect_err(|_| {
        let _ = fs::remove_file(&tmp);
    })
}

fn is_executable(p: &Path) -> bool {
    let Ok(meta) = fs::metadata(p) else {
        return false;
    };
    #[cfg(unix)]
    {
        meta.is_file() && meta.permissions().mode() & 0o111 != 0
    }
    #[cfg(not(unix))]
    {
        meta.is_file()
    }
}

fn is_stub(bytes: &[u8]) -> bool {
    let head = &bytes[..bytes.len().min(512)];
    String::from_utf8_lossy(head).contains(SIDECAR_STUB_MARKER)
}

/// Bundled binary for `s`: the sidecar name first, then the Cargo name (dev builds in `target/`).
fn read_bundled(env: &IntegrationEnv, s: Sidecar) -> Option<Vec<u8>> {
    let dir = env.sidecar_dir.as_ref()?;
    [s.bundle_name, s.name].iter().find_map(|n| {
        let p = dir.join(n);
        if !is_executable(&p) {
            return None;
        }
        fs::read(&p).ok().filter(|b| !b.is_empty() && !is_stub(b))
    })
}

// --- Git ---

fn apple_git_installed() -> bool {
    if !cfg!(target_os = "macos") {
        return true;
    }
    if Path::new("/Library/Developer/CommandLineTools/usr/bin/git").exists() {
        return true;
    }
    Command::new("/usr/bin/xcode-select")
        .arg("-p")
        .stdin(Stdio::null())
        .output()
        .ok()
        .filter(|o| o.status.success())
        .is_some_and(|o| PathBuf::from(String::from_utf8_lossy(&o.stdout).trim()).join("usr/bin/git").exists())
}

/// Git executable. Apps opened from Finder get a minimal `PATH`, so Homebrew locations are tried
/// too; `/usr/bin/git` is skipped when it is only Apple's stub (running it opens an install prompt).
pub fn find_git() -> Option<PathBuf> {
    // Only hits are cached, so installing Git while the app runs is picked up.
    static GIT: OnceLock<PathBuf> = OnceLock::new();
    if let Some(p) = GIT.get() {
        return Some(p.clone());
    }
    let mut dirs: Vec<PathBuf> = std::env::var_os("PATH")
        .map(|p| std::env::split_paths(&p).collect())
        .unwrap_or_default();
    dirs.extend(["/opt/homebrew/bin", "/usr/local/bin", "/usr/bin"].map(PathBuf::from));
    let found = dirs
        .into_iter()
        .map(|d| d.join("git"))
        .find(|p| is_executable(p) && (p != Path::new("/usr/bin/git") || apple_git_installed()))?;
    Some(GIT.get_or_init(|| found).clone())
}

