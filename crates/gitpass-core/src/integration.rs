#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum CheckState {
    Ok,
    /// Not installed yet; `apply` installs it.
    Missing,
    /// Installed by GitPass but stale; `apply` repairs it.
    Outdated,
    /// Something else owns the setting; see `current_value`.
    Conflict,
    Error,
}

#[derive(Debug, Clone, Serialize)]
pub struct ComponentStatus {
    pub state: CheckState,
    /// Short pt-PT sentence for the UI.
    pub summary: String,
    /// Value currently configured when it is not GitPass's (conflict).
    pub current_value: Option<String>,
    /// Value GitPass replaced or chains to (kept in the backup).
    pub previous_value: Option<String>,
}

impl ComponentStatus {
    fn new(state: CheckState, summary: impl Into<String>) -> Self {
        Self {
            state,
            summary: summary.into(),
            current_value: None,
            previous_value: None,
        }
    }

    fn current(mut self, v: Option<String>) -> Self {
        self.current_value = v;
        self
    }

    fn previous(mut self, v: Option<String>) -> Self {
        self.previous_value = v;
        self
    }
}

